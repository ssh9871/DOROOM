import { Engine } from '@babylonjs/core/Engines/engine';
import { Scene } from '@babylonjs/core/scene';
import { ArcRotateCamera } from '@babylonjs/core/Cameras/arcRotateCamera';
import { HemisphericLight } from '@babylonjs/core/Lights/hemisphericLight';
import { DirectionalLight } from '@babylonjs/core/Lights/directionalLight';
import { Vector3 } from '@babylonjs/core/Maths/math.vector';
import { Color4 } from '@babylonjs/core/Maths/math.color';
import { loadModel } from '../src/room/model';

const canvas = document.querySelector('canvas')!;
const engine = new Engine(canvas, true, { preserveDrawingBuffer: true, alpha: true });
const scene = new Scene(engine);
scene.clearColor = new Color4(0, 0, 0, 0);
const camera = new ArcRotateCamera('preview', -Math.PI / 2 - .3, 1.35, 3.8, new Vector3(0, 1, 0), scene);
camera.fov = .7;
new HemisphericLight('ambient', new Vector3(0, 1, 1), scene).intensity = 1.5;
new DirectionalLight('sun', new Vector3(-1, -2, 2), scene).intensity = 2;
const pet = new URLSearchParams(location.search).get('model') === 'pet';
const model = await loadModel(scene, pet ? 'pet/simple-cat.glb' : 'avatar/robot.glb', 1.9);
model.actor.rotation.y = Math.PI;
if (!pet) model.container.animationGroups.find(group => group.name.endsWith('|Idle'))?.start(true);
await scene.whenReadyAsync();
scene.render();
const download = document.createElement('a');
download.id = 'preview-download';
download.download = pet ? 'pet.png' : 'avatar.png';
download.href = canvas.toDataURL('image/png');
download.textContent = 'Download preview';
document.body.append(download);
document.querySelector('output')!.textContent = 'ready';
engine.runRenderLoop(() => scene.render());
