import { createPetState, pet, shopItems } from './pets.ts';

let checks = 0;
function assert(condition: boolean, message: string) {
  if (!condition) throw new Error(message);
  checks++;
}
const progressKey = 'doroom.pet-progress';
const legacyKey = 'doroom.equipped-pet';
const values = new Map<string, string>();
const storage = () => ({ getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); }, removeItem: (key: string) => { values.delete(key); } });
const fresh = (cells = 1000, hunger = 50, affection = 50, experience = 0) => {
  values.clear();
  values.set(progressKey, JSON.stringify({ version: 2, user: { id: 'user-default', nickname: '테스트', cells, items: { 'pet-food-001': 1, 'pet-ball-001': 1 } }, pets: { [pet.id]: { level: 1, experience, hunger, affection } } }));
  return createPetState(storage);
};
const food = shopItems[0]!;
const ball = shopItems[1]!;
const unchanged = (state: ReturnType<typeof createPetState>, action: () => unknown, message: string) => {
  const before = JSON.stringify({ user: state.user, pet: state.pet });
  action();
  assert(before === JSON.stringify({ user: state.user, pet: state.pet }), message);
};
let state = createPetState(storage);
assert(!state.equipped && state.user.cells === 1000, 'JSON defaults');
state.setEquipped(true);
assert(createPetState(storage).equipped, 'Equipment saved');
state.setEquipped(false);
assert(!createPetState(storage).equipped, 'Unequip saved');
values.clear(); values.set(legacyKey, pet.id);
assert(createPetState(storage).equipped && values.has(progressKey), 'Legacy equipment migrated');
values.clear(); values.set(legacyKey, 'unknown');
assert(!createPetState(storage).equipped, 'Unknown legacy ID rejected');
state = fresh(50);
state.buy(food.id);
assert(state.user.cells === 0 && state.user.items[food.id] === 2, 'Exact price purchase');
assert(createPetState(storage).user.cells === 0, 'Purchase restored');
state = fresh(49);
assert(state.buy(food.id).includes('셀이 부족'), 'Insufficient cells message');
unchanged(state, () => state.buy(food.id), 'Insufficient purchase unchanged');
unchanged(state, () => state.buy('unknown'), 'Unknown purchase unchanged');
state = fresh();
state.interact(pet.id, food.id);
assert(state.pet.hunger === 70 && state.pet.affection === 50 && state.user.items[food.id] === 0, 'Food only increases hunger and consumes one');
state.interact(pet.id, ball.id);
assert(state.pet.affection === 70 && state.user.items[ball.id] === 0 && state.pet.experience === 0, 'Toy only increases affection, no experience');
assert(!state.equipped, 'Interactions work unequipped');
unchanged(state, () => state.interact(pet.id, food.id), 'Empty stock unchanged');
unchanged(state, () => state.interact('unknown', ball.id), 'Unknown pet unchanged');
unchanged(state, () => state.interact(pet.id, 'unknown'), 'Unknown item unchanged');
state = fresh(1000, 95, 99);
state.interact(pet.id, food.id); state.interact(pet.id, ball.id);
assert(state.pet.hunger === 100 && state.pet.affection === 100, 'Stats capped');
state.buy(food.id);
unchanged(state, () => state.interact(pet.id, food.id), 'Full stat does not waste item');
state = fresh(100, 50, 50, 100);
assert(state.canGrow, 'Exact growth requirements');
state.grow(pet.id);
assert(state.pet.level === 2 && state.pet.experience === 0 && state.user.cells === 0 && state.requiredExperience === 200 && state.growthCost === 200, 'One level growth and new requirements');
unchanged(state, () => state.grow(pet.id), 'Repeat growth unchanged');
assert(createPetState(storage).pet.level === 2, 'Growth restored');
state = fresh(99, 50, 50, 100);
assert(!state.canGrow, 'Growth needs cells');
unchanged(state, () => state.grow(pet.id), 'Insufficient growth cells unchanged');
state = fresh(1000, 50, 50, 99);
assert(!state.canGrow, 'Growth needs full experience');
unchanged(state, () => state.grow(pet.id), 'Insufficient experience unchanged');
unchanged(state, () => state.grow('unknown'), 'Unknown growth pet unchanged');
values.set(progressKey, '{broken'); state = createPetState(storage);
assert(state.recovered && state.user.cells === 1000, 'Broken JSON recovery');
fresh();
const bad = JSON.parse(values.get(progressKey)!);
bad.user.cells = -10; bad.user.items[food.id] = .5; bad.user.items.unknown = 8;
bad.pets[pet.id] = { level: 0, experience: 999, hunger: -1, affection: 101 }; bad.equippedId = 'unknown';
values.set(progressKey, JSON.stringify(bad)); state = createPetState(storage);
assert(state.recovered && state.user.cells === 1000 && state.user.items[food.id] === 0 && !('unknown' in state.user.items), 'Invalid currency, quantities, unknown IDs');
assert(state.pet.level === 1 && state.pet.experience === pet.experience && state.pet.hunger === pet.hunger && state.pet.affection === pet.affection && !state.equipped, 'Invalid progress recovery');
fresh(); const missing = JSON.parse(values.get(progressKey)!); delete missing.pets; values.set(progressKey, JSON.stringify(missing));
assert(createPetState(storage).pet.level === 1, 'Missing new fields default');
values.set(progressKey, JSON.stringify({ version: 77 }));
assert(createPetState(storage).recovered, 'Unknown version recovery');
values.set(progressKey, JSON.stringify({ version: 2, user: { id: 'other-user' } }));
assert(createPetState(storage).recovered, 'Unknown user rejected');
state = fresh(); const view = state.user; view.cells = 0; view.items[food.id] = 99;
assert(state.user.cells === 1000 && state.user.items[food.id] === 1, 'Read views cannot mutate state');
const blocked = createPetState(() => { throw new Error('Storage blocked'); });
assert(!blocked.persistent, 'Blocked storage read handled');
blocked.setEquipped(true); blocked.buy(food.id);
assert(blocked.equipped && blocked.user.cells === 950 && !blocked.persistent, 'Memory state survives write failure');
blocked.setEquipped(false);
assert(!blocked.equipped, 'Memory unequip survives write failure');
state = fresh();
for (let i = 0; i < 25; i++) state.buy(food.id);
assert(state.user.cells === 0 && state.user.items[food.id] === 21, 'Rapid purchases cannot overspend');
state = fresh(); const overflow = JSON.parse(values.get(progressKey)!); overflow.user.items[food.id] = Number.MAX_SAFE_INTEGER; values.set(progressKey, JSON.stringify(overflow)); state = createPetState(storage);
unchanged(state, () => state.buy(food.id), 'Stock overflow rejected');
state = fresh(900, 100, 100, 0);
const previous = JSON.parse(values.get(progressKey)!);
previous.version = 1;
previous.equippedId = pet.id;
values.set(progressKey, JSON.stringify(previous));
state = createPetState(storage);
assert(state.pet.hunger === 50 && state.pet.affection === 50 && state.pet.experience === 100, 'Manual test baseline migrated');
assert(state.user.cells === 900 && state.user.items[food.id] === 1 && state.equipped, 'Migration preserves purchases and equipment');
state.interact(pet.id, food.id);
state = createPetState(storage);
assert(state.pet.hunger === 70 && state.user.items[food.id] === 0, 'Migration applies once and later progress survives reload');
console.log(`Pet state: ${checks} checks passed`);
